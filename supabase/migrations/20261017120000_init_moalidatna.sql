-- Resolves the internal sign-in e-mail for a generator name (kind = 'account')
-- or a worker phone (kind = 'worker'). Unknown identifiers get a decoy address
-- of the same shape, so the endpoint does not reveal which names exist.
create or replace function public.login_email(p_kind text, p_identifier text)
returns text
language plpgsql stable security definer
set search_path = ''
as $$
declare
  v_identifier text := btrim(coalesce(p_identifier, ''));
  v_user_id    uuid;
  v_email      text;
begin
  if p_kind = 'account' then
    select a.user_id into v_user_id
      from public.accounts a
     where a.generator_name = v_identifier and a.is_active;
  elsif p_kind = 'worker' then
    select w.user_id into v_user_id
      from public.workers w
      join public.accounts a on a.id = w.generator_id
     where w.phone = v_identifier and w.is_active and a.is_active;
  end if;

  if v_user_id is not null then
    select u.email into v_email from auth.users u where u.id = v_user_id;
  end if;

  return coalesce(
    v_email,
    'u' || md5(coalesce(p_kind, '') || ':' || v_identifier) || '@moalidatna.app'
  );
end;
$$;

-- Who am I? → { type, generator_id, generator_name, phone, worker_id, worker_name }
create or replace function public.my_profile()
returns jsonb
language sql stable security definer
set search_path = ''
as $$
  select coalesce(
    (select jsonb_build_object(
              'type', 'account',
              'generator_id', a.id,
              'generator_name', a.generator_name,
              'phone', a.phone,
              'worker_id', null,
              'worker_name', null)
       from public.accounts a
      where a.user_id = auth.uid() and a.is_active),
    (select jsonb_build_object(
              'type', 'worker',
              'generator_id', a.id,
              'generator_name', a.generator_name,
              'phone', w.phone,
              'worker_id', w.id,
              'worker_name', w.name)
       from public.workers w
       join public.accounts a on a.id = w.generator_id
      where w.user_id = auth.uid() and w.is_active and a.is_active)
  );
$$;

create or replace function private.require_manager()
returns bigint
language plpgsql stable security definer
set search_path = ''
as $$
declare
  v_generator_id bigint;
begin
  select a.id into v_generator_id
    from public.accounts a
   where a.user_id = auth.uid() and a.is_active;
  if v_generator_id is null then
    raise exception 'هذه العملية متاحة لمدير المولدة فقط' using errcode = '42501';
  end if;
  return v_generator_id;
end;
$$;
