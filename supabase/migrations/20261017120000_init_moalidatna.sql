-- Manager: add a worker who can sign in with phone + password.
create or replace function public.create_worker(p_name text, p_phone text, p_password text)
returns public.workers
language plpgsql security definer
set search_path = ''
as $$
declare
  v_generator_id bigint := private.require_manager();
  v_worker       public.workers;
begin
  if exists (select 1 from public.workers w where w.phone = btrim(p_phone)) then
    raise exception 'رقم الهاتف مستخدم مسبقاً' using errcode = 'P0001';
  end if;

  insert into public.workers (generator_id, user_id, name, phone)
  values (v_generator_id, private.create_auth_user(p_password), btrim(p_name), btrim(p_phone))
  returning * into v_worker;
  return v_worker;
end;
$$;

-- Manager: edit a worker's name / phone.
create or replace function public.update_worker(p_worker_id bigint, p_name text, p_phone text)
returns public.workers
language plpgsql security definer
set search_path = ''
as $$
declare
  v_generator_id bigint := private.require_manager();
  v_worker       public.workers;
begin
  if exists (select 1 from public.workers w where w.phone = btrim(p_phone) and w.id <> p_worker_id) then
    raise exception 'رقم الهاتف مستخدم مسبقاً' using errcode = 'P0001';
  end if;

  update public.workers
     set name = btrim(p_name), phone = btrim(p_phone)
   where id = p_worker_id and generator_id = v_generator_id
  returning * into v_worker;
  if v_worker.id is null then
    raise exception 'العامل غير موجود' using errcode = 'P0001';
  end if;
  return v_worker;
end;
$$;

-- Manager: reset a worker's password.
create or replace function public.set_worker_password(p_worker_id bigint, p_password text)
returns void
language plpgsql security definer
set search_path = ''
as $$
declare
  v_generator_id bigint := private.require_manager();
  v_user_id      uuid;
begin
  select w.user_id into v_user_id
    from public.workers w
   where w.id = p_worker_id and w.generator_id = v_generator_id;
  if not found then
    raise exception 'العامل غير موجود' using errcode = 'P0001';
  end if;

  if v_user_id is null then
    update public.workers set user_id = private.create_auth_user(p_password) where id = p_worker_id;
  else
    perform private.set_auth_password(v_user_id, p_password);
  end if;
end;
$$;

-- Manager: deactivate (soft-delete) or re-activate a worker. Deactivated
-- workers are banned in auth, so they cannot sign in or refresh a session.
create or replace function public.set_worker_active(p_worker_id bigint, p_active boolean)
returns public.workers
language plpgsql security definer
set search_path = ''
as $$
declare
  v_generator_id bigint := private.require_manager();
  v_worker       public.workers;
begin
  update public.workers
     set is_active = p_active
   where id = p_worker_id and generator_id = v_generator_id
  returning * into v_worker;
  if v_worker.id is null then
    raise exception 'العامل غير موجود' using errcode = 'P0001';
  end if;

  if v_worker.user_id is not null then
    perform private.set_auth_banned(v_worker.user_id, not p_active);
  end if;
  return v_worker;
end;
$$;

