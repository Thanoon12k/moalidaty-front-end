-- ─── Session helpers (used by RLS) ───────────────────────────────────────────

-- The generator the signed-in user belongs to (manager or active worker).
create or replace function private.current_generator_id()
returns bigint
language sql stable security definer
set search_path = ''
as $$
  select coalesce(
    (select a.id
       from public.accounts a
      where a.user_id = auth.uid() and a.is_active),
    (select w.generator_id
       from public.workers w
       join public.accounts a on a.id = w.generator_id
      where w.user_id = auth.uid() and w.is_active and a.is_active)
  );
$$;

create or replace function private.is_manager()
returns boolean
language sql stable security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.accounts a
     where a.user_id = auth.uid() and a.is_active
  );
$$;

create or replace function private.current_worker_id()
returns bigint
language sql stable security definer
set search_path = ''
as $$
  select w.id
    from public.workers w
    join public.accounts a on a.id = w.generator_id
   where w.user_id = auth.uid() and w.is_active and a.is_active;
$$;

revoke all on function private.current_generator_id() from public;
revoke all on function private.is_manager()           from public;
revoke all on function private.current_worker_id()    from public;
grant execute on function private.current_generator_id() to authenticated;
grant execute on function private.is_manager()           to authenticated;
grant execute on function private.current_worker_id()    to authenticated;

-- ─── Auth user management (internal) ─────────────────────────────────────────

create or replace function private.internal_email(p_user_id uuid)
returns text
language sql immutable
set search_path = ''
as $$
  select 'u' || replace(p_user_id::text, '-', '') || '@moalidatna.app';
$$;

create or replace function private.check_password(p_password text)
returns void
language plpgsql immutable
set search_path = ''
as $$
begin
  if p_password is null or char_length(p_password) < 6 then
    raise exception 'كلمة المرور يجب أن تكون 6 أحرف على الأقل' using errcode = 'P0001';
  end if;
  if char_length(p_password) > 72 then
    raise exception 'كلمة المرور طويلة جداً' using errcode = 'P0001';
  end if;
end;
$$;

-- Creates a confirmed e-mail/password user in auth.users and returns its id.
create or replace function private.create_auth_user(p_password text)
returns uuid
language plpgsql security definer
set search_path = ''
as $$
declare
  v_id    uuid := gen_random_uuid();
  v_email text := private.internal_email(v_id);
begin
  perform private.check_password(p_password);

  insert into auth.users (
    instance_id, id, aud, role, email, encrypted_password,
    email_confirmed_at, raw_app_meta_data, raw_user_meta_data,
    created_at, updated_at,
    confirmation_token, recovery_token, email_change_token_new, email_change
  ) values (
    '00000000-0000-0000-0000-000000000000', v_id, 'authenticated', 'authenticated',
    v_email, extensions.crypt(p_password, extensions.gen_salt('bf', 10)),
    now(), '{"provider": "email", "providers": ["email"]}'::jsonb, '{}'::jsonb,
    now(), now(),
    '', '', '', ''
  );

  insert into auth.identities (
    id, user_id, provider_id, provider, identity_data,
    last_sign_in_at, created_at, updated_at
  ) values (
    gen_random_uuid(), v_id, v_id::text, 'email',
    jsonb_build_object('sub', v_id::text, 'email', v_email, 'email_verified', true),
    now(), now(), now()
  );

  return v_id;
end;
$$;

create or replace function private.set_auth_password(p_user_id uuid, p_password text)
returns void
language plpgsql security definer
set search_path = ''
as $$
begin
  perform private.check_password(p_password);
  update auth.users
     set encrypted_password = extensions.crypt(p_password, extensions.gen_salt('bf', 10)),
         updated_at = now()
   where id = p_user_id;
end;
$$;

-- Banned users cannot sign in or refresh their session. (A far-future date
-- rather than 'infinity', which the auth server cannot parse.)
create or replace function private.set_auth_banned(p_user_id uuid, p_banned boolean)
returns void
language sql security definer
set search_path = ''
as $$
  update auth.users
     set banned_until = case when p_banned then now() + interval '100 years' else null end,
         updated_at = now()
   where id = p_user_id;
$$;

revoke all on function private.internal_email(uuid)                from public;
revoke all on function private.check_password(text)                from public;
revoke all on function private.create_auth_user(text)              from public;
revoke all on function private.set_auth_password(uuid, text)       from public;
revoke all on function private.set_auth_banned(uuid, boolean)      from public;

-- ─── Admin: create a generator account (run from the SQL editor) ─────────────
--   select private.admin_create_account('مولدة الكرخ', '07701111111', 'secret123');

create or replace function private.admin_create_account(
  p_generator_name text,
  p_phone          text,
  p_password       text
)
returns bigint
language plpgsql security definer
set search_path = ''
as $$
declare
  v_user_id uuid;
  v_id      bigint;
begin
  v_user_id := private.create_auth_user(p_password);
  insert into public.accounts (user_id, generator_name, phone)
  values (v_user_id, btrim(p_generator_name), btrim(p_phone))
  returning id into v_id;
  return v_id;
end;
$$;

create or replace function private.admin_set_account_password(p_account_id bigint, p_password text)
returns void
language plpgsql security definer
set search_path = ''
as $$
declare
  v_user_id uuid;
begin
  select user_id into v_user_id from public.accounts where id = p_account_id;
  if v_user_id is null then
    v_user_id := private.create_auth_user(p_password);
    update public.accounts set user_id = v_user_id where id = p_account_id;
  else
    perform private.set_auth_password(v_user_id, p_password);
  end if;
end;
$$;

revoke all on function private.admin_create_account(text, text, text)       from public;
revoke all on function private.admin_set_account_password(bigint, text)     from public;

