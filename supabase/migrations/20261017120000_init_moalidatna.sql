-- ════════════════════════════════════════════════════════════════════════════
--  مولداتنا — initial Supabase schema
--  Ported from the Django backend (mainapp/models.py):
--    Account → accounts, Worker → workers, Subscriber → subscribers,
--    Budget → budgets, Receipt → receipts
--
--  Auth model
--    • Every generator manager (account) and every worker owns one row in
--      auth.users with an internal e-mail (u<uuid-hex>@moalidatna.app).
--    • The app never shows that e-mail: it calls public.login_email() with the
--      generator name (manager) or phone (worker) and signs in with the result.
--    • Accounts are created by the admin only (private.admin_create_account),
--      workers by their manager (public.create_worker). Public sign-up is off.
--
--  Authorization (replaces IsGeneratorAuthenticated / IsAccountOnly)
--    • Every row is scoped to the caller's generator by RLS.
--    • Managers can do everything inside their generator.
--    • Workers can read everything in their generator, add subscribers and
--      add receipts (always recorded under their own worker id).
-- ════════════════════════════════════════════════════════════════════════════

create extension if not exists pgcrypto with schema extensions;

create schema if not exists private;
revoke all on schema private from public;
grant usage on schema private to authenticated;

-- ─── Tables ──────────────────────────────────────────────────────────────────

create table public.accounts (
  id             bigint generated by default as identity primary key,
  user_id        uuid references auth.users (id) on delete set null,
  generator_name text not null,
  phone          text not null,
  is_active      boolean not null default true,
  date_created   timestamptz not null default now(),
  constraint accounts_user_id_key        unique (user_id),
  constraint accounts_generator_name_key unique (generator_name),
  constraint accounts_phone_key          unique (phone),
  constraint accounts_generator_name_len check (char_length(btrim(generator_name)) between 2 and 100),
  constraint accounts_phone_format       check (phone ~ '^\+?[0-9]{7,15}$')
);
comment on table public.accounts is 'حسابات المولدات — one row per generator (its manager logs in with generator_name).';

create table public.workers (
  id           bigint generated by default as identity primary key,
  generator_id bigint not null references public.accounts (id) on delete cascade,
  user_id      uuid references auth.users (id) on delete set null,
  name         text not null,
  phone        text not null,
  is_active    boolean not null default true,
  date_created timestamptz not null default now(),
  constraint workers_user_id_key  unique (user_id),
  constraint workers_phone_key    unique (phone),
  constraint workers_name_len     check (char_length(btrim(name)) between 2 and 100),
  constraint workers_phone_format check (phone ~ '^\+?[0-9]{7,15}$')
);
comment on table public.workers is 'العمال — collectors who log in with their phone number.';

create table public.subscribers (
  id              bigint generated by default as identity primary key,
  generator_id    bigint not null references public.accounts (id) on delete cascade,
  name            text not null,
  circuit_number  text not null,
  ambers          integer not null,
  phone           text not null default '',
  date_subscribed date not null default current_date,
  is_active       boolean not null default true,
  date_created    timestamptz not null default now(),
  constraint subscribers_name_len     check (char_length(btrim(name)) between 2 and 100),
  constraint subscribers_circuit_len  check (char_length(btrim(circuit_number)) between 1 and 20),
  constraint subscribers_ambers_range check (ambers between 1 and 1000),
  constraint subscribers_phone_format check (phone = '' or phone ~ '^\+?[0-9]{7,15}$')
);
comment on table public.subscribers is 'المشتركون — soft-deleted with is_active = false to keep receipt history.';

create table public.budgets (
  id           bigint generated by default as identity primary key,
  generator_id bigint not null references public.accounts (id) on delete cascade,
  year         integer not null,
  month        integer not null,
  amber_price  numeric(10, 2) not null default 0,
  date_created timestamptz not null default now(),
  constraint budgets_one_per_month unique (generator_id, year, month),
  constraint budgets_year_range    check (year between 2000 and 2100),
  constraint budgets_month_range   check (month between 1 and 12),
  constraint budgets_price_range   check (amber_price >= 0)
);
comment on table public.budgets is 'الميزانيات — the price of one amber for a given month.';

create table public.receipts (
  id            bigint generated by default as identity primary key,
  generator_id  bigint not null references public.accounts (id) on delete cascade,
  subscriber_id bigint not null references public.subscribers (id) on delete cascade,
  worker_id     bigint references public.workers (id) on delete set null,
  year          integer not null,
  month         integer not null,
  amber_price   numeric(10, 2) not null,
  amount_paid   numeric(12, 2) not null,
  notes         text not null default '',
  date_received timestamptz not null default now(),
  constraint receipts_one_per_month unique (generator_id, subscriber_id, year, month),
  constraint receipts_year_range    check (year between 2000 and 2100),
  constraint receipts_month_range   check (month between 1 and 12),
  constraint receipts_price_range   check (amber_price >= 0),
  constraint receipts_amount_range  check (amount_paid >= 0),
  constraint receipts_notes_len     check (char_length(notes) <= 500)
);
comment on table public.receipts is 'الإيصالات — one payment per subscriber per month.';

