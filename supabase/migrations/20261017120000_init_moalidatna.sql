-- Rows created through the API always belong to the caller's generator.
-- (Admin / seed inserts run without a JWT and keep the generator_id they pass.)
create or replace function private.stamp_generator_id()
returns trigger
language plpgsql security definer
set search_path = ''
as $$
declare
  v_generator_id bigint := private.current_generator_id();
begin
  if v_generator_id is not null then
    new.generator_id := v_generator_id;
  end if;
  return new;
end;
$$;

create trigger subscribers_stamp_generator before insert on public.subscribers
  for each row execute function private.stamp_generator_id();
create trigger budgets_stamp_generator before insert on public.budgets
  for each row execute function private.stamp_generator_id();

-- Receipts: stamp generator + worker, validate references, fill price/amount.
create or replace function private.receipts_before_write()
returns trigger
language plpgsql security definer
set search_path = ''
as $$
declare
  v_generator_id bigint := private.current_generator_id();
  v_worker_id    bigint := private.current_worker_id();
  v_sub          public.subscribers;
begin
  if tg_op = 'INSERT' then
    if v_generator_id is not null then
      new.generator_id := v_generator_id;
    end if;
    -- A worker always collects in their own name.
    if v_worker_id is not null then
      new.worker_id := v_worker_id;
    end if;
  end if;

  select * into v_sub from public.subscribers s where s.id = new.subscriber_id;
  if v_sub.id is null or v_sub.generator_id <> new.generator_id then
    raise exception 'المشترك غير موجود في هذه المولدة' using errcode = 'P0001';
  end if;

  if new.worker_id is not null and not exists (
    select 1 from public.workers w
     where w.id = new.worker_id and w.generator_id = new.generator_id
  ) then
    raise exception 'العامل غير موجود في هذه المولدة' using errcode = 'P0001';
  end if;

  if new.amber_price is null then
    select b.amber_price into new.amber_price
      from public.budgets b
     where b.generator_id = new.generator_id
       and b.year = new.year and b.month = new.month;
    if new.amber_price is null then
      raise exception 'لا توجد ميزانية مسجلة لهذا الشهر' using errcode = 'P0001';
    end if;
  end if;

  if new.amount_paid is null then
    new.amount_paid := new.amber_price * v_sub.ambers;
  end if;

  return new;
end;
$$;

create trigger receipts_before_write before insert or update on public.receipts
  for each row execute function private.receipts_before_write();

revoke all on function private.stamp_generator_id()    from public;
revoke all on function private.receipts_before_write() from public;

