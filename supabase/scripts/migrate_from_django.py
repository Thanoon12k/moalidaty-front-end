#!/usr/bin/env python3
"""Move the data of the old Django server (db.sqlite3) into Supabase.

Reads the mainapp_* tables of the Django SQLite database and prints one SQL
transaction that recreates every account, worker, subscriber, budget and
receipt in the Supabase schema (supabase/migrations), keeping their ids.

Django stores pbkdf2 password hashes, which Supabase Auth cannot verify, so
every manager and worker gets a new password. They are written to a CSV file
(--credentials) — hand them out and delete the file afterwards.

Usage
    python3 supabase/scripts/migrate_from_django.py path/to/db.sqlite3 \
        --credentials credentials.csv > django_data.sql

    # then, against a project that has the migrations but NO seed data:
    psql "$SUPABASE_DB_URL" -v ON_ERROR_STOP=1 -f django_data.sql
    # (or paste django_data.sql into the Supabase SQL editor)

Options
    --password PASS   give everyone the same password instead of random ones
"""
import argparse
import csv
import re
import secrets
import sqlite3
import string
import sys

PHONE_RE = re.compile(r"^\+?[0-9]{7,15}$")


def q(value):
    """SQL literal."""
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def clean_phone(raw):
    return re.sub(r"[\s\-()]", "", raw or "")


def new_password(fixed):
    if fixed:
        return fixed
    alphabet = string.ascii_letters + string.digits
    return "".join(secrets.choice(alphabet) for _ in range(10))


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("sqlite_path")
    parser.add_argument("--credentials", default="credentials.csv",
                        help="where to write the new logins (default: credentials.csv)")
    parser.add_argument("--password", help="same password for every user (min 6 chars)")
    args = parser.parse_args()

    if args.password is not None and len(args.password) < 6:
        sys.exit("--password must be at least 6 characters")

    db = sqlite3.connect(args.sqlite_path)
    db.row_factory = sqlite3.Row
    rows = lambda table: db.execute(f"select * from {table} order by id").fetchall()

    out = []
    creds = []
    warnings = []
    emit = out.append

    emit("-- Generated by supabase/scripts/migrate_from_django.py")
    emit("begin;")
    emit("do $$ begin")
    emit("  if exists (select 1 from public.accounts) then")
    emit("    raise exception 'Target project already has accounts — run this on an empty project (skip seed.sql).';")
    emit("  end if;")
    emit("end $$;")
    emit("")

    for a in rows("mainapp_account"):
        phone = clean_phone(a["phone"])
        if not PHONE_RE.match(phone):
            sys.exit(f"Account {a['id']} ({a['generator_name']}) has an invalid phone: {a['phone']!r}")
        password = new_password(args.password)
        creds.append(("manager", a["generator_name"], password))
        emit(
            "insert into public.accounts (id, user_id, generator_name, phone, is_active, date_created) values "
            f"({a['id']}, private.create_auth_user({q(password)}), {q(a['generator_name'].strip())}, "
            f"{q(phone)}, {q(bool(a['is_active']))}, {q(a['date_created'])});"
        )

    for w in rows("mainapp_worker"):
        phone = clean_phone(w["phone"])
        if not PHONE_RE.match(phone):
            sys.exit(f"Worker {w['id']} ({w['name']}) has an invalid phone: {w['phone']!r}")
        password = new_password(args.password)
        if w["is_active"]:
            creds.append(("worker", phone, password))
        emit(
            "insert into public.workers (id, generator_id, user_id, name, phone, is_active, date_created) values "
            f"({w['id']}, {w['generator_id']}, private.create_auth_user({q(password)}), {q(w['name'].strip())}, "
            f"{q(phone)}, {q(bool(w['is_active']))}, {q(w['date_created'])});"
        )
        if not w["is_active"]:
            emit(f"select private.set_auth_banned(user_id, true) from public.workers where id = {w['id']};")

    for s in rows("mainapp_subscriber"):
        phone = clean_phone(s["phone"])
        if phone and not PHONE_RE.match(phone):
            warnings.append(f"subscriber {s['id']} ({s['name']}): dropped invalid phone {s['phone']!r}")
            phone = ""
        emit(
            "insert into public.subscribers (id, generator_id, name, circuit_number, ambers, phone, "
            "date_subscribed, is_active, date_created) values "
            f"({s['id']}, {s['generator_id']}, {q(s['name'].strip())}, {q(s['circuit_number'].strip())}, "
            f"{s['ambers']}, {q(phone)}, {q(s['date_subscribed'])}, {q(bool(s['is_active']))}, "
            f"{q(s['date_created'])});"
        )

    for b in rows("mainapp_budget"):
        emit(
            "insert into public.budgets (id, generator_id, year, month, amber_price, date_created) values "
            f"({b['id']}, {b['generator_id']}, {b['year']}, {b['month']}, {b['amber_price']}, "
            f"{q(b['date_created'])});"
        )

    for r in rows("mainapp_receipt"):
        emit(
            "insert into public.receipts (id, generator_id, subscriber_id, worker_id, year, month, "
            "amber_price, amount_paid, notes, date_received) values "
            f"({r['id']}, {r['generator_id']}, {r['subscriber_id']}, {q(r['worker_id'])}, {r['year']}, "
            f"{r['month']}, {r['amber_price']}, {r['amount_paid']}, {q(r['notes'] or '')}, "
            f"{q(r['date_received'])});"
        )

    emit("")
    emit("-- Continue the id sequences after the imported rows.")
    for table in ("accounts", "workers", "subscribers", "budgets", "receipts"):
        emit(
            f"select setval(pg_get_serial_sequence('public.{table}', 'id'), "
            f"coalesce((select max(id) from public.{table}), 0) + 1, false);"
        )
    emit("commit;")

    print("\n".join(out))

    with open(args.credentials, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["role", "login", "new_password"])
        writer.writerows(creds)

    for w in warnings:
        print(f"warning: {w}", file=sys.stderr)
    print(f"{len(creds)} logins written to {args.credentials}", file=sys.stderr)


if __name__ == "__main__":
    main()
